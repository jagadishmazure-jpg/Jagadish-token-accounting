"""Regenerate docs/results.md and the README results block from results files and the real test count.

python scripts/render_docs.py          # write
python scripts/render_docs.py --check  # fail if docs drift from the results files
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from count_tests import count  # noqa: E402

CATS = ("english", "code", "json", "hindi", "telugu", "emoji")
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def tables(tests: int) -> tuple[str, str]:
    r = json.loads((ROOT / "results.json").read_text())
    loc = json.loads((ROOT / "results_local_model.json").read_text())
    out = ["### Tokens per word (tokens per character in brackets)", "", "| tokenizer | " + " | ".join(CATS) + " |", "|---" * (len(CATS) + 1) + "|"]
    for n, v in r["compare"].items():
        out.append(f"| {n} | " + " | ".join(f"{v[c]['tokens_per_word']} ({v[c]['tokens_per_char']})" for c in CATS) + " |")
    if r.get("spm_unknown_pct"):
        out += ["", "SentencePiece unknown-piece share by type (%): " + ", ".join(f"{c} {r['spm_unknown_pct'][c]}" for c in CATS)]
    out += [
        "",
        f"### Where the input tokens go ({r['accounting_tokenizer']})",
        "",
        "| request | total | system | tools | docs | history | user | format overhead |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n, v in r["accounting"].items():
        s = v["share_pct"]
        out.append(
            f"| {n} | {v['tokens']['total']} | " + " | ".join(f"{s[k]}%" for k in ("system", "tools", "docs", "history", "user", "format_overhead")) + " |"
        )
    out += [
        "",
        f"### Local model reconciliation ({loc['model']}, prompt tokens)",
        "",
        "| request | reported | own tokenizer + template | cl100k + template | o200k + template | content only, no framing | user text only |",
        "|---|---|---|---|---|---|---|",
    ]
    for n, row in loc["rows"].items():
        b, nv = row["by_counter"], row["naive_model_tokenizer"]
        cells = [b[k]["prompt_drift_pct"] for k in ("model-own-tokenizer", "cl100k_base", "o200k_base")] + [
            nv[k]["prompt_drift_pct"] for k in ("content_without_framing", "user_text_only")
        ]
        out.append(f"| {n} | {row['reported_prompt']} | " + " | ".join(f"{c:+}%" for c in cells) + " |")
    out += [
        "",
        "### Quick-rule error (signed %, estimate vs real count)",
        "",
        "| tokenizer | rule | " + " | ".join(CATS) + " |",
        "|---" * (len(CATS) + 2) + "|",
    ]
    for n, v in r["estimate_error_pct"].items():
        for rule, label in (("chars_rule", "4 chars/token"), ("words_rule", "1.3 tokens/word")):
            out.append(f"| {n} | {label} | " + " | ".join(f"{v[c][rule]:+}" for c in CATS) + " |")
    out += [
        "",
        "### Gateway and ledger replay (1,200 requests at ~110 RPS, per-customer budget 150,000 tokens; output lengths simulated)",
        "",
        "| mode | outcomes | trimmed | bill (illustrative prices) | input / output cost |",
        "|---|---|---|---|---|",
    ]
    for k in ("replay_trim", "replay_reject"):
        v = r[k]
        out.append(
            f"| {v['mode']} | "
            + ", ".join(f"{a} {b}" for a, b in v["outcomes"].items())
            + f" | {v['trimmed']} | ${v['total_cost_usd']} | ${v['input_cost_usd']} / ${v['output_cost_usd']} |"
        )
    body = "\n".join(out)
    results_md = (
        "# Results\n\nGenerated by `python scripts/render_docs.py` from `results.json` and `results_local_model.json`. Do not edit by hand.\n\n"
        + f"Tests: **{tests}**\n\n"
        + body
        + "\n"
    )
    readme_block = f"{START}\nTests: **{tests}** (printed by `python scripts/count_tests.py`)\n\n{body}\n{END}"
    return results_md, readme_block


def main(argv: list[str]) -> int:
    results_md, block = tables(count())
    readme = (ROOT / "README.md").read_text()
    a, b = readme.index(START), readme.index(END) + len(END)
    new_readme = readme[:a] + block + readme[b:]
    rp = ROOT / "docs" / "results.md"
    if "--check" in argv:
        bad = [p for p, want in ((rp, results_md), (ROOT / "README.md", new_readme)) if not p.exists() or p.read_text() != want]
        if bad:
            print("docs out of date:", ", ".join(str(p.relative_to(ROOT)) for p in bad))
            return 1
        print("docs match results files and test count")
        return 0
    rp.write_text(results_md)
    (ROOT / "README.md").write_text(new_readme)
    print("docs rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
